class StudentEntity {
  final String id;
  final String name;
  final String grade;
  final String address;
  final String diacon;
  final String whatsapp;
  final String phone;
  final String notes;

  StudentEntity({
    required this.id,
    required this.name,
    required this.grade,
    required this.address,
    required this.diacon,
    required this.whatsapp,
    required this.phone,
    required this.notes,
  });
}
